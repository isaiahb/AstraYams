"""Record finite-motor lift commissioning and export an orbitable CAD replay."""
import argparse,json,shutil
from pathlib import Path
import mujoco
import numpy as np
from astrafactory.tower_lift import TowerLiftEnv
import render_strawberry_specimen as exporter

ROOT=Path(__file__).resolve().parents[1]


def record(folder,seconds):
    env=TowerLiftEnv(folder,horizon_s=seconds);env.reset();m,d=env.model,env.data
    qs=[d.qpos.copy()];ts=[0.];forces=[];infos=[]
    for i in range(round(seconds/env.dt)):
        action=np.zeros(m.nu)
        # Arms hold a parking posture while the lift travels 0.12 m and returns.
        # Setpoint rate is bounded; actual motion is generated by the actuators.
        if 1.0<=d.time<2.5:action[env.lift]=1
        elif 3.2<=d.time<4.7:action[env.lift]=-1
        obs,reward,term,trunc,info=env.step(action)
        qs.append(d.qpos.copy());ts.append(float(d.time));forces.append(d.actuator_force.copy());infos.append(info)
        if term:break
    out=folder/'commission';out.mkdir(exist_ok=True)
    np.savez_compressed(out/'rollout.npz',qpos=qs,t=ts,actuator_forces=forces)
    result=dict(infos[-1],scope='Scripted lift commissioning; arm setpoints held constant. No learned harvest.',
                actuator_force_limits=m.actuator_forcerange.tolist(),
                peak_actuator_force_N_or_Nm=np.max(np.abs(forces),axis=0).tolist(),
                lift_command_rate_limit_m_s=float(env.rate[env.lift]),
                lift_height_min_m=float(min(q[env.qids[env.lift]] for q in qs)),
                lift_height_max_m=float(max(q[env.qids[env.lift]] for q in qs)))
    (out/'result.json').write_text(json.dumps(result,indent=2)+'\n')
    print(folder.name,json.dumps(result),flush=True)
    return result


def main():
    p=argparse.ArgumentParser();p.add_argument('--root',type=Path,default=ROOT/'runs/tower-lift-v1')
    p.add_argument('--template',type=Path,default=ROOT/'tools/templates/tower-lift-review.html');p.add_argument('--seconds',type=float,default=5.5);p.add_argument('--layout-only',action='store_true');a=p.parse_args();root=a.root.resolve()
    results={}
    config=json.loads((root/'config.json').read_text())
    for kind in config.get('embodiments',['so101','yam']):
        folder=root/kind
        if a.layout_only:phase='layout'
        else:phase='commission';results[kind]=record(folder,a.seconds)
        exporter.P=folder;exporter.export([phase])
        payload=json.loads((folder/phase/'replay.json').read_text())
        if config['frame'].get('design')=='photo_rig':
            prefix='Photographed rig reconstruction; no robot arms; ' if kind=='rig' else 'Proposed '+kind+' arm bridge on reconstructed rig; '
        else:prefix='Photo-informed lift workcell; stock '+kind+' arms; '
        payload['scope']=prefix+('static layout' if a.layout_only else 'recorded finite-motor commissioning')
        (folder/'replay.json').write_text(json.dumps(payload,separators=(',',':')))
    (root/'commission.json').write_text(json.dumps(results,indent=2)+'\n')
    shutil.copy2(a.template,root/'index.html')
    print(root/'index.html')


if __name__=='__main__':main()
